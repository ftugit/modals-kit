import { defineParams } from '@sveltejs/kit/params'

/**
 * Матчеры сегментов адреса. Форма адреса принадлежит роутеру: сегмент,
 * не прошедший матчер, не матчится, и SvelteKit отвечает настоящим 404
 * до `load` — ни компонент, ни домен такой id не видят, на странице и
 * в запросах данных модалок одинаково. Существование записи матчер не
 * судит: подходящий по форме id без записи — «не найдено» данными
 * от `load` (модалке брошенный из `load` 404 не обслужить).
 *
 * Файл — plain JS сознательно: сборка Кита загружает его обычным
 * `import()` Node для проверки матчеров, а Node 22.17 `.ts` не читает.
 */
export const params = defineParams({
  /** UUID — формат id аккаунтов и записей проекта (`[id=uuid]`). */
  uuid: (param) =>
    /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(param)
      ? param
      : undefined,
})
