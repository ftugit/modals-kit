// Источники цепочки как состояние ВСЕГО приложения (этап B).
//
// Раньше это был $state страницы /modals, и смена источников пересобирала
// не только ядро, но и хост (страница стояла в {#key}) — панель источников
// приходилось выносить из-под хоста, и её select на узком экране жил без
// слоя хоста («свой фон», осмотр 1.10-2 №32).
//
// Теперь хост один и живёт в корневом layout, а источники — модульное
// состояние: его пишет панель, читает layout при сборке ядра. Аналог
// «сигнала, доступного из любого места»: руна $state в модуле.
//
// Объект-обёртка, а не экспорт массива: переназначить (`demoSources.list =
// next`) можно только через свойство — живая привязка экспорта в Svelte
// работает на чтение, но не на запись извне модуля.
export const demoSources = $state<{ list: string[] }>({ list: ['url', 'local', 'memory'] })
