// Общий гидратационный гейт панелей («jsOnly остаётся в shell», §6.4) — этап 6.
//
// Мерило одно для всех трёх демо-панелей: управление выключено, пока компонент
// не обновлён (смонтирован), — и включается после; причина формулируется тут же,
// единственный текст на репозиторий (тот же несёт helper пагинаторной панели).
//
// `$app/environment.browser` для этого не годится: он честен на сервере, но на
// клиенте становится истиной с первой же отрисовки — в том числе до оживления,
// и «выключено до гидратации» превращается в «зависит от того, перерисовался ли
// узел». Флаг ниже переворачивается ровно на монтировании.
import { onMount } from 'svelte'

/** Причина для helper/noscript: одна строка на оболочку, панель и форму. */
export const JS_ONLY_REASON = 'доступно после загрузки JavaScript'

/** `true`, пока компонент не смонтирован (SSR, no-JS и момент до гидратации). */
export function useJsOnly(): () => boolean {
  let hydrated = $state(false)
  onMount(() => {
    hydrated = true
  })
  return () => !hydrated
}
