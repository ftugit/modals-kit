/**
 * Одна формула паузы на весь проект: опрос, повторы транспорта, форма.
 *
 * Было две копии — экспонента в `create.ts` (с джиттером) и своя в опросчике
 * демо (без джиттера, потолок 60 с). Одинаковые по смыслу, они расходились в
 * деталях: правку «потолок важнее степени» пришлось бы делать дважды.
 *
 * Пауза = `base · 2^(attempt − 1)`, не больше `cap`. `random` — источник джиттера:
 * по умолчанию `() => 1` (без разброса, детерминированно — так его проверяют
 * тесты опросчика); транспорт передаёт генератор случайных чисел своего `clock`.
 */

/**
 * Пауза перед попыткой `attempt`.
 * @param attempt Номер попытки, начиная с 1 (первая пауза — после первого сбоя).
 * @param baseMs Базовая пауза.
 * @param capMs Потолок: «сервер лежит» не лечится чаще, чем раз в паузу.
 * @param random Джиттер в долях от потолка шага; `1` — ровно потолок шага.
 * @returns Пауза в миллисекундах.
 */
export function backoffDelay(
  attempt: number,
  baseMs: number,
  capMs: number,
  random: () => number = () => 1,
): number {
  const step = Math.max(1, attempt)
  const ceiling = Math.min(capMs, baseMs * 2 ** (step - 1))
  return Math.round(ceiling * random())
}
