/**
 * Хранилища приложения — единственное место, где решается, что куда передать
 * (`docs/design/cache-pg-store.md`). Места в коде получают хранилище явно и
 * не знают, что за ним стоит.
 *
 * `localStore` — память процесса: кэши внешних API, короткая память условного
 * GET, всё, где расхождение между инстансами стоит лишнего запроса, а не ошибки.
 * Каждое место берёт свою область (`localStore.scope('имя', { max })`) — со своим
 * потолком, чтобы поток уникальных ключей в одном месте не вытеснял записи
 * другого.
 *
 * `sharedStore` — Postgres (`pgStore` поверх `db`, таблица модели `cacheKv`):
 * общее между инстансами, с атомарными `add`/`incr`. Только местам, где
 * расхождение инстансов = ошибка: бронь отправки форм, которые и так пишут в
 * базу, и заявки с токеном (фото R4). Форма, которой база не нужна, получает
 * память: иначе отметка «уже принято» стала бы её единственной поездкой на
 * сервер БД и новой причиной отказа. Фабрика соединения не открывает (`db`
 * ленивый), поэтому экспорт ничего не стоит до первого обращения. На
 * dev-движке PGlite база одна на процесс — охват там честно равен памяти.
 */
import { memoryStore } from '#lib/cache/index.js'
import { pgStore } from '#hooks/cache-db.js'
import { db } from './db.server.js'

export const localStore = memoryStore()

export const sharedStore = pgStore(db)
