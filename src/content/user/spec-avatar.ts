/**
 * Параметры картинки профиля: каким должен получиться файл.
 *
 * Единственное место этих чисел. Конфиг их не дублирует: ключей вроде
 * `avatarEdge` больше нет — иначе одно и то же значение жило бы дважды и
 * расходилось при правке.
 *
 * Это набор параметров, а не поле и не функция: `raw` (бюджет тела) сюда не
 * входит — это работа транспорта. Читают трое: примитив поля (`photoConvert` —
 * он и приводит картинку), описание формы (предел веса файла) и проверка
 * `avatar-spec` (формат, кадр, вес). Сервер картинку НЕ приводит: прийти должен
 * уже готовый кадр — см. `docs/plan-queue.md`.
 */
export interface SpecAvatar {
  /** Ширина готового кадра, px. */
  readonly width: number
  /** Высота готового кадра, px. */
  readonly height: number
  /** Предел веса готового файла, байт. */
  readonly maxBytes: number
  /** Конечное расширение готового файла. */
  readonly format: 'jpeg' | 'png' | 'webp'
}

/** Параметры профиля по умолчанию: 200 × 200, 20 КиБ, JPEG. */
export const specAvatar: SpecAvatar = {
  width: 200,
  height: 200,
  maxBytes: 20_480,
  format: 'jpeg',
}
